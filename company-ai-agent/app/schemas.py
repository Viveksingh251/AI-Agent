"""Pydantic Request, Response, and Data Transfer Schemas."""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Payload sent by client to interact with the AI Agent."""

    message: str = Field(
        ...,
        min_length=1,
        description="User query, command, or operational prompt",
        examples=["Find all open critical tickets and who they are assigned to."],
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Unique session identifier for multi-turn conversational context",
        examples=["session_abc123"],
    )
    system_override: Optional[str] = Field(
        default=None,
        description="Optional custom system prompt instruction for this turn",
    )


class ToolCallRecord(BaseModel):
    """Log entry representing an individual tool invocation by the agent."""

    id: str = Field(..., description="Unique tool call ID generated by LLM")
    tool_name: str = Field(..., description="Name of the invoked tool")
    arguments: Dict[str, Any] = Field(
        default_factory=dict,
        description="Arguments passed to the tool",
    )
    result: Any = Field(
        default=None,
        description="Data or status returned by the tool",
    )


class ExecutionStep(BaseModel):
    """A single reasoning and execution step in the ReAct loop."""

    step_number: int = Field(..., description="Sequential step index (1, 2, ...)")
    thought: Optional[str] = Field(
        default=None,
        description="Reasoning or explanation formulated before or during tool use",
    )
    tool_call: Optional[ToolCallRecord] = Field(
        default=None,
        description="Tool invocation data if a tool was executed during this step",
    )


class ChatResponse(BaseModel):
    """Final synthesized response returned by the AI agent."""

    session_id: str = Field(..., description="Session identifier for thread continuity")
    answer: str = Field(..., description="Synthesized response delivered to user")
    tools_used: List[str] = Field(
        default_factory=list,
        description="List of distinct tools employed to answer the prompt",
    )
    steps: List[ExecutionStep] = Field(
        default_factory=list,
        description="Detailed trace of reasoning and tool calls executed",
    )
    iterations: int = Field(
        default=1,
        description="Number of ReAct thought-action iterations completed",
    )
    timestamp: datetime = Field(
        ...,
        description="UTC timestamp of response generation",
    )


class MessageItem(BaseModel):
    """Represents a message stored in persistent session memory."""

    id: Optional[int] = None
    role: str = Field(..., description="Role: 'user', 'assistant', 'system', or 'tool'")
    content: Optional[str] = Field(default=None, description="Text body of message")
    tool_calls_json: Optional[str] = Field(default=None, description="Serialized tool calls")
    timestamp: Optional[datetime] = None


class SessionSummary(BaseModel):
    """Brief metadata summary of a conversation session."""

    session_id: str
    title: str
    message_count: int
    created_at: datetime
    updated_at: datetime


class SessionHistoryResponse(BaseModel):
    """Full chronological history for an active session."""

    session_id: str
    messages: List[MessageItem]
    total_messages: int


class ToolDefinition(BaseModel):
    """Specification of an agent tool and its JSON Schema parameters."""

    name: str = Field(..., description="Unique identifier for the tool")
    description: str = Field(..., description="Instructions detailing what tool does")
    parameters: Dict[str, Any] = Field(
        ...,
        description="JSON schema describing expected input arguments",
    )


class HealthCheckResponse(BaseModel):
    """Detailed health check diagnostic output."""

    status: str = Field(..., description="'healthy' or 'degraded'")
    llm_status: str = Field(..., description="'connected' or 'unavailable'")
    database_status: str = Field(..., description="'connected' or 'unavailable'")
    active_tools: int = Field(..., description="Count of registered tools")
    environment: str = Field(..., description="Current deployment environment")
    timestamp: datetime = Field(..., description="UTC timestamp of diagnostic")

